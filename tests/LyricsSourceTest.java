import com.visionmod.VisionLyricsSource;
import com.visionmod.VisionLyricsLookup;
import com.visionmod.SystemMediaTrack;
import com.visionmod.LyricsResult;
import java.nio.file.*;
public class LyricsSourceTest {
    private static int checks;
    private static void check(boolean ok,String message){checks++;if(!ok)throw new AssertionError(message);}
    public static void main(String[] args)throws Exception{
        Path dir=Path.of(System.getProperty("visionmod.test.config"));
        check(!VisionLyricsSource.mediaConnected(),"no phantom connection");
        check(VisionLyricsSource.current()==null,"empty source has no invented words");
        VisionLyricsSource.receiveMediaTrack("Spotify","Artist","Song",1600,true);
        check(VisionLyricsSource.current().isEmpty(),"title is not presented as song lyrics while lookup is pending");
        VisionLyricsSource.setMediaLyrics("Artist","Song","[00:00.00]First\n[00:01.50]Second\n[00:02.00]Third");
        check(VisionLyricsSource.current().equals("Second"),"paused playback position");
        Thread.sleep(100);
        check(VisionLyricsSource.current().equals("Second"),"pause does not advance clock");
        VisionLyricsSource.receiveMediaTrack("Spotify","Artist","Song",0,true);
        check(VisionLyricsSource.current().equals("First"),"seek backwards");
        VisionLyricsSource.receiveMediaTrack("Spotify","Other Artist","Next",0,true);
        check(VisionLyricsSource.current().isEmpty(),"new track clears old lyric without a title substitute");
        VisionLyricsSource.setMediaLyrics("Artist","Song","[00:00]STALE");
        check(!VisionLyricsSource.current().contains("STALE"),"late response cannot replace new song");
        VisionLyricsSource.receiveMediaTrack("Spotify","Other Artist","Next",0,false);
        VisionLyricsSource.setMediaLyrics("Other Artist","Next","[00:00]Start\n[00:00.150]Advance");
        Thread.sleep(200);
        check(VisionLyricsSource.current().equals("Advance"),"playing clock advances");
        VisionLyricsSource.setMediaLyrics("Other Artist","Next","[00:00]Start\n[00:00.150]Advance\n[00:00.250]\n[00:00.500]End");
        VisionLyricsSource.receiveMediaTrack("Spotify","Other Artist","Next",300,true);
        check(VisionLyricsSource.current().isEmpty(),"instrumental gap remains silent rather than cycling manual words");
        VisionLyricsSource.receiveMediaTrack(new SystemMediaTrack("Spotify","Next","Other Artist",0,false,1000,2,true),System.nanoTime()-100_000_000);
        check(VisionLyricsSource.current().equals("Advance"),"capture timestamp and playback rate survive client queue delay");
        VisionLyricsSource.receiveMediaTrack(new SystemMediaTrack("Spotify","Next","Other Artist",0,false,1000,1,false),System.nanoTime());
        check(VisionLyricsSource.current().equals("Start")&&VisionLyricsSource.plainMode()&&VisionLyricsSource.progress()<0,"missing player position exposes actual words without claiming sync");
        VisionLyricsSource.movePlainLine(1);
        check(VisionLyricsSource.current().equals("Advance"),"untimed words can be read without inventing playback timing");
        VisionLyricsSource.setMediaLyrics("Other Artist","Next",new LyricsResult("","Одна строка\nДругая строка","Test provider"));
        check(VisionLyricsSource.plainMode()&&VisionLyricsSource.current().equals("Одна строка"),"plain lyrics work even without an LRC timeline");
        VisionLyricsSource.movePlainLine(-1);
        check(VisionLyricsSource.current().equals("Другая строка"),"plain line navigation wraps safely");
        VisionLyricsSource.receiveMediaTrack("Spotify","Other Artist","Next",0,true);
        VisionLyricsSource.setMediaLyrics("Other Artist","Next",new LyricsResult("[00:00]Timed","Plain alternative","Test provider"));
        check(VisionLyricsSource.current().equals("Timed")&&!VisionLyricsSource.plainMode(),"real timed lyrics take priority over plain alternatives");
        VisionLyricsSource.receiveMediaTrack(new SystemMediaTrack("YandexMusic","Same Song","Same Artist",0,true,1000,1,true,"https://music.yandex.ru/album/1/track/123?from=one"),System.nanoTime());
        VisionLyricsSource.setMediaLyrics("Same Artist","Same Song","[00:00]Stable words");
        VisionLyricsSource.receiveMediaTrack(new SystemMediaTrack("YandexMusic","Same Song","Same Artist",0,true,1000,1,true,"https://music.yandex.ru/album/1/track/123?from=two"),System.nanoTime());
        check(VisionLyricsSource.current().equals("Stable words"),"Yandex URL tracking parameters cannot erase the current lyric");
        VisionLyricsSource.receiveMediaTrack(new SystemMediaTrack("YandexMusic","Same Song","Same Artist",0,true,1000,1,true,"https://music.yandex.ru/album/1/track/124"),System.nanoTime());
        check(VisionLyricsSource.current().isEmpty(),"a different Yandex track ID invalidates the old words even with identical labels");
        VisionLyricsSource.clearMediaTrack();VisionLyricsLookup.clear();
        check(!VisionLyricsSource.mediaConnected(),"off clears media");
        Files.createDirectories(dir.resolve("visionmod"));
        Files.writeString(dir.resolve("visionmod/lyrics.lrc"),"[00:00.00]Offline");
        Thread.sleep(1100);VisionLyricsSource.poll();
        check(VisionLyricsSource.current().equals("Offline"),"offline LRC fallback");
        Files.writeString(dir.resolve("visionmod/lyrics.lrc"),"[00:00.00]Offline\n[00:01.00]Positioned");
        Thread.sleep(1100);VisionLyricsSource.poll();
        VisionLyricsSource.receiveMediaTrack("Spotify","Artist","Song",1500,true);
        check(VisionLyricsSource.current().equals("Positioned"),"local LRC uses native song position while music plays");
        VisionLyricsSource.clearMediaTrack();
        Files.delete(dir.resolve("visionmod/lyrics.lrc"));
        Thread.sleep(1100);VisionLyricsSource.poll();
        check(VisionLyricsSource.current()==null,"deleted LRC clears old text");
        check(VisionLyricsSource.importText("\uFEFF[ti:Example]\n[00:00:00]<00:00.00>First\n[00:02.00] Second\n[00:04.00] "),"import handles BOM, enhanced LRC, and colon fractions");
        check(VisionLyricsSource.plainMode()&&VisionLyricsSource.current().equals("First"),"import without media starts in plain mode without exposing timing tags or metadata");
        check(VisionLyricsSource.setManualClock(2500,false)&&!VisionLyricsSource.plainMode()&&VisionLyricsSource.current().equals("Second"),"paused manual clock renders correct offline LRC line");
        check(VisionLyricsSource.setManualClock(4500,false)&&VisionLyricsSource.current().isEmpty(),"manual clock preserves instrumental gaps");
        check(!VisionLyricsSource.importText("[00:00.00]\n[00:02.00]")&&VisionLyricsSource.hasImport(),"empty LRC does not replace imported words");
        VisionLyricsSource.useAutomaticClock();
        VisionLyricsSource.receiveMediaTrack("Local","Test","Missing lyrics",2500,true);
        VisionLyricsSource.setMediaLyrics("Test","Missing lyrics","[00:00]Catalog result");
        check(VisionLyricsSource.current().equals("Second"),"import takes priority and follows the native song clock");
        VisionLyricsSource.clearMediaTrack();
        VisionLyricsSource.receiveMediaTrack("Local","Test","Missing lyrics",2500,true);
        check(VisionLyricsSource.current().equals("Second"),"same song reconnect retains its imported words");
        VisionLyricsSource.receiveMediaTrack("Local","Test","Next song",2500,true);
        check(!VisionLyricsSource.hasImport()&&VisionLyricsSource.current().isEmpty(),"previous import does not carry across a track change");
        check(VisionLyricsSource.importText("Совсем редкая песня\nЕщё строка"),"plain clipboard text imports without a catalog");
        check(!VisionLyricsSource.setManualClock(0,true)&&VisionLyricsSource.plainMode(),"plain words cannot start a timed clock");
        VisionLyricsSource.movePlainLine(1);
        check(VisionLyricsSource.current().equals("Ещё строка"),"imported plain words page independently");
        VisionLyricsSource.clearImport();
        check(VisionLyricsSource.current().isEmpty(),"removing import returns to the active native track");
        VisionLyricsSource.receiveMediaTrack(new SystemMediaTrack("Local","Next song","Test",0,false,9000,1,false),System.nanoTime());
        VisionLyricsSource.setMediaLyrics("Test","Next song","[00:00]First\n[00:00.100]Second");
        check(VisionLyricsSource.setManualClock(0,true),"manual clock starts for automatic LRC without native position");
        Thread.sleep(150);
        check(VisionLyricsSource.current().equals("Second"),"manual clock advances on real elapsed time");
        VisionLyricsSource.useAutomaticClock();
        check(VisionLyricsSource.plainMode(),"restoring auto clock without media position falls back to manual pages");
        System.out.println("PASS: "+checks+" lyric source assertions (test scheduler, not Minecraft)");
    }
}
